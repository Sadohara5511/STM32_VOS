/**
 * 以下は、GCC（GNUアセンブラ）構文で書かれた、実際のコンテキスト切り替えを行うアセンブリコードです。
 * VOS_TCB_t 構造体に合わせた処理を行うため、現在の実行中タスクのTCBを指すグローバルポインタ g_vos_current_tcb と、
 * 次に実行すべき最高優先度のTCBを指す g_vos_next_tcb がシステム側に存在するものとして記述しています。
 * また、構造体の先頭から 7番目のメンバ（オフセット24バイト） にある sp（スタックポインタ保存用）を書き換える前提としています。
 */
/**
 * @function PendSV_Handler
 * 実行中だったタスクのレジスタ（R4-R11）をスタックに退避し、次のREADY状態のタスクのスタックからレジスタを復元して実行を再開します。
 */
    .syntax unified
    .cpu cortex-m4
    .thumb

    /* 外部参照するグローバル変数の宣言 */
    .extern g_vos_current_tcb    /* 現在実行中のTCBへのポインタ (VOS_TCB_t*) */
    .extern g_vos_next_tcb       /* 次に実行するTCBへのポインタ (VOS_TCB_t*) */

    .global PendSV_Handler
    .type PendSV_Handler, %function

PendSV_Handler:
    /* =========================================================================
     * 1. 割込み禁止（排他制御）
     * ========================================================================= */
    cpsid   i

    /* =========================================================================
     * 2. 現在の実行中タスクのコンテキスト（レジスタ）をスタックへ保存
     * ========================================================================= */
    /* 現在実行中のタスクがあるか確認 (初回起動時などは NULL の可能性があるため) */
    ldr     r0, =g_vos_current_tcb
    ldr     r1, [r0]
    cbz     r1, .L_restore_context    /* NULLなら保存をスキップして復元へ */

    /* ソフトウェアで退避が必要なレジスタ (R4 - R11) をスタックにプッシュ */
    mrs     r2, psp                   /* プロセススタックポインタ(PSP)を取得 */
    stmdb   r2!, {r4-r11}             /* PSPを減算しながらR4-R11を保存 */

    /* 新しいスタックポインタ(r2)を、現在のTCBの sp メンバに保存 */
    /* VOS_TCB_t内の sp は先頭から7番目(4バイト*6 = 24バイトオフセット)と仮定 */
    str     r2, [r1, #24]

    /* =========================================================================
     * 3. 次のタスクへのポインタの切り替え
     * ========================================================================= */
.L_restore_context:
    ldr     r2, =g_vos_next_tcb
    ldr     r3, [r2]                  /* r3 = g_vos_next_tcb */
    str     r3, [r0]                  /* g_vos_current_tcb = g_vos_next_tcb */

    /* =========================================================================
     * 4. 次のタスクのコンテキスト（レジスタ）をスタックから復元
     * ========================================================================= */
    /* 次のタスクのTCBからスタックポインタ(spメンバ: オフセット24)を読み出す */
    ldr     r2, [r3, #24]

    /* スタックからレジスタ (R4 - R11) をポップして復元 */
    ldmia   r2!, {r4-r11}             /* ポップと同時にr2(SPアドレス)を進める */
    msr     psp, r2                   /* 復元したSPをPSPレジスタに書き戻す */

    /* =========================================================================
     * 5. 割込み許可と、タスク空間（PSP）への戻り指示
     * ========================================================================= */
    cpsie   i

    /* 例外からの復帰コード (EXC_RETURN) を設定 */
    /* 0xFFFFFFFD は「スレッドモードに戻る」「スタックはPSPを使用する」を意味する */
    ldr     lr, =0xFFFFFFFD
    bx      lr                        /* 例外復帰（自動的にR0-R3, R12, LR, PC, xPSRが復元される） */

    .size PendSV_Handler, .-PendSV_Handler
